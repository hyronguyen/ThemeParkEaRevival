"""Read-only recovery of bundled defaults; server entity prices are not invented."""
import json
import struct
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def recover():
    symbols = json.loads((ROOT / 'analysis/ios/symbols.json').read_text())
    symbol = next(s for s in symbols if s['name'].endswith('XPTable_values'))
    with zipfile.ZipFile(ROOT / 'resource/Theme_Park_1.8.3_ios_5.1.1.ipa') as archive:
        binary = archive.read('Payload/ThemePark.app/ThemePark')
    # Global::_Construct allocates 0x41 entries and copies exactly 0x104 bytes.
    values = list(struct.unpack_from('<65i', binary, symbol['file_offset']))
    assert all(0 < n < 1000000 for n in values)
    return values, symbol

if __name__ == '__main__':
    values, symbol = recover()
    report = dict(source='iOS 1.8.3 bundled fallback, server ConfigKeyValue may override',
                  symbol=symbol['name'], file_offset=symbol['file_offset'],
                  xp_per_level=values, price_table_recovered=False,
                  evidence=['Global::_Construct 0x15f376: 65 entries, 260-byte copy',
                            'Control::incrementProgress 0x8619c: XPTable[level-1], subtract on level-up',
                            'Android entity parser: price, priceSuperTickets, sellPrice, upgradeCost',
                            'Android LoadData parser: ConfigKeyValue XPTable'])
    (ROOT / 'analysis/economy_defaults.json').write_text(json.dumps(report, indent=2)+'\n')
    header = '// Generated by tools/recover_economy_defaults.py; bundled iOS fallback, not live server balance.\n#pragma once\n#include <array>\nnamespace playtest {\ninline constexpr std::array<int,65> originalXP = {{\n'
    header += ',\n'.join('    '+','.join(map(str, values[i:i+10])) for i in range(0,65,10))
    header += '\n}};\n}\n'
    (ROOT / 'src/original_economy.h').write_text(header)
    print('Recovered 65 original XP thresholds; entity prices remain unverified.')
